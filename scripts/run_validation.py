"""Validation study on synthetic data, where the truth is known.

Checks that (1) the theory and the Monte Carlo simulator agree, (2) the estimators recover the
parameters of a simulated market, and (3) using the intraday volatility profile improves the
schedule. Writes figures to docs/figures and numbers to docs/validation_results.md.

    python scripts/run_validation.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from optexec import ac, calibration as cal, data, plots, simulate, volatility as vol  # noqa: E402

FIG = ROOT / "docs" / "figures"
OUT = ROOT / "docs" / "validation_results.md"


def md_table(df: pd.DataFrame, fmt: str = "{:.4g}") -> str:
    cols = [df.index.name or ""] + list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for idx, row in df.iterrows():
        cells = [str(idx)] + [fmt.format(v) if isinstance(v, (int, float, np.floating)) else str(v) for v in row]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main() -> None:
    report: list[str] = ["# Validation results (synthetic data)\n", "Generated by `scripts/run_validation.py`. All numbers come from simulated data where the true parameters are known.\n"]

    # ------------------------------------------------------------------ 1. theory vs Monte Carlo
    S0 = 30_000.0
    p = ac.ACParams(X=300.0, T=60.0, N=60, sigma=S0 * 8e-4, gamma=S0 * 1.1e-5, eta=S0 * 1.1e-5, S0=S0)
    kts = [0.0, 0.5, 1.0, 2.0, 4.0, 8.0]
    plots.plot_trajectories(p, [0, 1, 2, 4, 8], FIG / "trajectories.png")
    mc, rows = {}, []
    for k in kts:
        lam = ac.lambda_for_kappa(p, k)
        n = ac.optimal_trades(p, lam)
        stats = simulate.summarize(simulate.simulate_shortfall(p, n, n_paths=200_000, seed=11))
        mc[k] = (stats.mean, stats.std, stats.stderr_of_mean)
        e_th, v_th = ac.expected_cost(p, n), ac.variance_cost(p, n)
        rows.append({"kappa_T": k, "E theory": e_th, "E MC": stats.mean, "z-score": (stats.mean - e_th) / stats.stderr_of_mean,
                     "std theory": np.sqrt(v_th), "std MC": stats.std, "std rel. error": stats.std / np.sqrt(v_th) - 1})
    tab = pd.DataFrame(rows).set_index("kappa_T")
    plots.plot_mc_check(p, kts, mc, FIG / "mc_check.png")
    plots.plot_frontier(p, FIG / "frontier.png", mc_points={f"{k}": (mc[k][0], mc[k][1]) for k in kts})
    report += ["\n## 1. Closed form against Monte Carlo (200,000 paths each)\n", "The same random numbers are used in every row, so the z-scores are correlated.\n", md_table(tab), "\n![MC check](figures/mc_check.png)\n![Frontier](figures/frontier.png)\n![Trajectories](figures/trajectories.png)\n"]

    # ------------------------------------------------------------------ 2. calibration on a simulated market
    bars, truth = data.synthetic_market(n_days=90, seed=0)
    r = cal.log_returns(bars.close)
    q = cal.signed_imbalance(bars).loc[r.index]
    lin = cal.fit_linear_impact(q.to_numpy(), r.to_numpy())
    pw = cal.fit_power_impact(q.to_numpy(), r.to_numpy())
    rev = cal.fit_reversion(q, r)
    profile = cal.intraday_variance_profile(r)
    true_prof = pd.Series(truth["profile"] ** 2).groupby(np.arange(len(truth["profile"])) // 30 * 30 % (24 * 60)).mean()
    true_prof = (true_prof / true_prof.mean()).reindex(profile.index)
    corr = float(np.corrcoef(profile.to_numpy(), true_prof.to_numpy())[0, 1])
    plots.plot_impact_fit(pw, lin, FIG / "impact_fit.png", title="Synthetic market: price response to signed flow")
    plots.plot_vol_profile(profile, FIG / "vol_profile.png", truth=truth["profile"] ** 2 / np.mean(truth["profile"] ** 2))
    cal_tab = pd.DataFrame(
        {
            "true": [truth["delta"], truth["reversion_share"]],
            "estimated": [pw.delta, rev.lam_temporary / rev.lam_total.slope],
            "std error": [pw.delta_se, np.nan],
        },
        index=pd.Index(["impact exponent delta", "temporary share of impact"], name="parameter"),
    )
    report += [
        "\n## 2. Calibration on a simulated market (90 days of 1-minute bars)\n",
        md_table(cal_tab, "{:.3f}"),
        f"\nLinear fit through the origin: R² = {lin.r2:.3f}. The log-log fit of the power law has R² = {pw.r2_loglog:.3f} on {len(pw.bins)} bins, so a linear impact is clearly the wrong shape when the true exponent is {truth['delta']}.",
        f"\nCorrelation between the estimated and true intraday variance profile: {corr:.3f}.\n",
        "\n![Impact fit](figures/impact_fit.png)\n![Volatility profile](figures/vol_profile.png)\n",
    ]

    # volatility forecasts
    table = vol.evaluate_horizon_forecasts(r, horizon=60, train_frac=0.6)
    scores = vol.score_forecasts(table)
    plots.plot_vol_scores(scores, FIG / "vol_scores.png")
    gf = table.attrs["garch_fit"]
    report += [
        "\n## 3. Volatility forecasts (out of sample, 60-minute horizon)\n",
        md_table(scores.rename_axis("method")),
        f"\nGARCH(1,1) on the training part: alpha = {gf.alpha:.3f}, beta = {gf.beta:.3f}, persistence = {gf.persistence:.4f}.\n",
        "\n![Volatility scores](figures/vol_scores.png)\n",
    ]

    # ------------------------------------------------------------------ 4. time-varying volatility
    sigma_bar = float(r.std())
    # an 8-hour order, so that the volatility changes a lot within the window
    long_p = ac.ACParams(X=3000.0, T=480.0, N=480, sigma=sigma_bar, gamma=rev.lam_permanent, eta=rev.lam_temporary, eps=1e-4, S0=1.0)
    lam_long = ac.lambda_for_kappa(long_p, 2.0)
    fixed = 0.5 * long_p.gamma * long_p.X**2 + long_p.eps * long_p.X  # does not depend on the schedule
    tv_rows = []
    for label, start in [("starts 02:00 UTC (quiet)", 2 * 60), ("starts 06:00 UTC (volatility rising)", 6 * 60)]:
        sig = cal.sigma_schedule(profile, sigma_bar, start, long_p.N, long_p.tau, 30)
        n_c = ac.optimal_trades(long_p, lam_long)
        n_t = ac.optimal_trades_time_varying(long_p, lam_long, sig)
        u_c = ac.utility(long_p, n_c, lam_long, sig) - fixed
        u_t = ac.utility(long_p, n_t, lam_long, sig) - fixed
        tv_rows.append({"window": label, "controllable cost, constant-vol schedule": u_c,
                        "controllable cost, intraday-vol schedule": u_t, "improvement %": 100 * (1 - u_t / u_c)})
        if start == 6 * 60:
            plots.plot_time_varying(np.arange(long_p.N) * long_p.tau, sig, n_c, n_t, FIG / "time_varying.png")
    tv = pd.DataFrame(tv_rows).set_index("window")
    report += [
        "\n## 4. Using the intraday volatility profile\n",
        "An 8-hour order of 3,000 units. Objective `E + lambda V` without the constant permanent-impact term (which no schedule can change), "
        "both schedules evaluated under the volatility that actually applies in the window; lower is better:\n",
        md_table(tv, "{:.4g}"),
        "\n![Time-varying](figures/time_varying.png)\n",
    ]

    OUT.write_text("\n".join(report), encoding="utf-8")
    print("\n".join(report[:6]))
    print("written", OUT)


if __name__ == "__main__":
    main()
